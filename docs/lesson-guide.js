function purchase(farm, id) {
  const item = UPGRADES.find(upgrade => upgrade.id === id);
  const left = item.price - farm.coins;
  return left > 0
    ? {text: 'Собирай урожай. До открытия «' + item.name + '» осталось ' + left + ' ◈.', shop: true}
    : {text: 'Монет хватает. Открой мастерскую и купи «' + item.name + '».', shop: true};
}

function nextStep(farm, index) {
  switch (index) {
    case 0: return {text: 'Собери спелую пшеницу под роботом. После запуска счётчик урожая должен стать равен 1.'};
    case 1: return purchase(farm, 'loops');
    case 2: return farm.used.includes('while') ? purchase(farm, 'expand2') : {text: 'Поручи роботу повторять сбор без нового нажатия на «Запустить».'};
    case 3: return farm.visited.length < 4 ? {text: 'Посети каждую клетку поля. Уже посещено ' + farm.visited.length + ' из 4.'} : purchase(farm, 'plant');
    case 4: return farm.planted < 4 ? {text: 'Посади растение на свободной грядке. Удачных посадок ' + farm.planted + ' из 4.'} : purchase(farm, 'senses');
    case 5: return farm.used.includes('if') ? purchase(farm, 'for') : {text: 'Пусть робот проверяет, созрело ли растение, прежде чем собирать его.'};
    case 6: return farm.used.includes('for') ? purchase(farm, 'grid4') : {text: 'Обойди ряд, задав число повторов. Сделай по шагу для каждой клетки.'};
    case 7: return farm.knows('water') ? {text: 'Полей растение и проверь, как изменилась влажность.'} : purchase(farm, 'water');
    case 8: return farm.knows('carrot') ? {text: 'Выращивай морковь на почве и собери хотя бы одну на склад.'} : purchase(farm, 'carrot');
    case 9:
      if (!farm.knows('beet')) return purchase(farm, 'beet');
      if (!farm.knows('sunflower')) return purchase(farm, 'sunflower');
      if (!farm.tiles.some(tile => tile.crop === 'sunflower')) return {text: 'Подготовь свободную клетку с почвой и 3 пшеницы. Посади подсолнух командой посадки, указав "sunflower".'};
      return {text: farm.used.includes('measure') ? 'Собери спелый подсолнух и получи энергию.' : 'Выращивай подсолнухи и измерь число лепестков под роботом.'};
    default: return {text: 'Сколько урожая твой робот может собрать за один обход? Проверь свою догадку.'};
  }
}

export function setupGuide() {
  const get = id => document.getElementById(id);
  const panel = get('thinkingGuide'), list = get('thinkingSteps');
  const toggle = get('lessonButton'), more = get('nextHint'), shop = get('goalShop');
  const headings = ['Посмотри на поле', 'Подбери команду', 'Проверь догадку'];
  let index, count = 0;

  function reveal() {
    const row = document.createElement('li'), title = document.createElement('strong');
    title.textContent = headings[count];
    row.append(title, document.createTextNode(guides[index][count]));
    list.append(row);
    count++;
    more.hidden = count === headings.length;
    more.textContent = count === 1 ? 'Как записать?' : 'Как проверить?';
    if (more.hidden) get('returnToCode').focus();
  }
  function close() { panel.hidden = true; toggle.setAttribute('aria-expanded', 'false'); }
  toggle.onclick = () => {
    if (!panel.hidden) { close(); return; }
    panel.hidden = false;
    toggle.setAttribute('aria-expanded', 'true');
    if (count === 0) reveal();
  };
  more.onclick = reveal;
  get('returnToCode').onclick = () => { close(); get('code').focus(); };
  shop.onclick = () => get('upgradesButton').click();
  return (farm, chapter) => {
    if (chapter !== index) {
      index = chapter; count = 0; close(); list.replaceChildren();
      more.hidden = false; toggle.hidden = chapter < 0;
    }
    const {text, shop: showShop} = nextStep(farm, chapter);
    get('miniLessonTask').textContent = text;
    shop.hidden = !showShop;
  };
}
